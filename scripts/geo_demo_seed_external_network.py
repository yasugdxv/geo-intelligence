def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--user-id", required=True)
    ap.add_argument("--apply", action="store_true")
    args = ap.parse_args()
    client = SupabaseClient(load_config())
    ident = IosIdentity(identity_id=args.user_id, assigned_role="analyst", authenticated=True)
    existing = {c["name"] for c in svc.list_contacts(client, ident, include_inactive=True)}
    made_c = made_l = skipped = 0
    for name, affiliation, expertise, intro, logs in DATA:
        if name in existing:
            print(f"  skip（同名のコンタクトが既にあります）: {name}")
            skipped += 1
            continue
        if not args.apply:
            print(f"  dry-run: {name} / {affiliation} / ログ{len(logs)}件")
            continue
        # 専門領域の欄（expertise_note）は、SQL 2026-10-14_geo_ia_extensions.sql が未適用の環境では使えないため、メモに書く
        c = svc.create_contact(client, ident, name=name, affiliation_title=affiliation,
                               memo=f"{TAG}専門領域: {expertise}。{intro}", owner_ids=[args.user_id])
        made_c += 1
        for day, memo in logs:
            svc.create_log(client, ident, contact_ids=[c["contact_id"]], contact_date=day, memo=f"{TAG}{memo}",
                           participant_ids=[args.user_id])
            made_l += 1
        print(f"  作成: {name}（ログ{len(logs)}件）")
    print(f"contacts_created={made_c} logs_created={made_l} skipped={skipped} apply={args.apply}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
